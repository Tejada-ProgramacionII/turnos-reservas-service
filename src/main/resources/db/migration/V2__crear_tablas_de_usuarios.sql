-- V2: usuarios finales y sus autoridades (modelo de usuario de JHipster, D-02).
--
-- Las tablas tienen nombre en español; las columnas siguen los nombres de JHipster.
-- El id lo genera la base. external_patient_id es el identificador estable que se
-- envía a la cátedra (D-03): lo genera el backend y nunca cambia.
CREATE TABLE usuarios (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login               VARCHAR(50)              NOT NULL,
    password_hash       VARCHAR(60)              NOT NULL,
    first_name          VARCHAR(50),
    last_name           VARCHAR(50),
    email               VARCHAR(254)             NOT NULL,
    image_url           VARCHAR(256),
    activated           BOOLEAN                  NOT NULL,
    lang_key            VARCHAR(10)              NOT NULL,
    external_patient_id UUID                     NOT NULL,
    created_by          VARCHAR(50)              NOT NULL,
    created_date        TIMESTAMP WITH TIME ZONE NOT NULL,
    last_modified_by    VARCHAR(50),
    last_modified_date  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_usuarios_login UNIQUE (login),
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT uk_usuarios_external_patient_id UNIQUE (external_patient_id)
);

-- Autoridades (roles) que puede tener un usuario.
CREATE TABLE autoridades (
    name VARCHAR(50) PRIMARY KEY
);

-- Qué autoridades tiene cada usuario (relación muchos a muchos).
CREATE TABLE usuario_autoridad (
    user_id        BIGINT      NOT NULL,
    authority_name VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, authority_name),
    CONSTRAINT fk_usuario_autoridad_usuario FOREIGN KEY (user_id) REFERENCES usuarios (id),
    CONSTRAINT fk_usuario_autoridad_autoridad FOREIGN KEY (authority_name) REFERENCES autoridades (name)
);

