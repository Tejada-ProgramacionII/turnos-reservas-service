-- V4: procesos de reserva (CU-04 a CU-10) y eventos Kafka ya procesados (D-06).
--
-- Cada proceso es de un usuario (D-13). Los datos del profesional son historial:
-- no reemplazan al catálogo vigente. reservation_process_id es el identificador
-- con el que la cátedra nombra al proceso en REST y en Kafka: queda NULL hasta
-- que se crea el hold, y nunca se repite.
CREATE TABLE procesos_reserva (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id             BIGINT                   NOT NULL,
    profesional_id         BIGINT                   NOT NULL,
    fecha                  DATE                     NOT NULL,
    hora_inicio            TIME                     NOT NULL,
    hora_fin               TIME                     NOT NULL,
    profesional_nombre     VARCHAR(100),
    profesional_apellido   VARCHAR(100),
    hold_id                VARCHAR(100),
    reservation_process_id VARCHAR(100),
    expires_at             TIMESTAMP WITH TIME ZONE,
    request_event_id       VARCHAR(100),
    mensaje_pedido         VARCHAR(500),
    telefono               VARCHAR(30),
    reservation_id         BIGINT,
    motivo                 VARCHAR(500),
    estado                 VARCHAR(20)              NOT NULL,
    creado_en              TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizado_en         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_procesos_reserva_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT uk_procesos_reserva_reservation_process_id UNIQUE (reservation_process_id)
);

-- "Mis reservas" (CU-07) busca siempre por usuario.
CREATE INDEX idx_procesos_reserva_usuario ON procesos_reserva (usuario_id);

-- Un evento con un event_id ya guardado no vuelve a producir efectos (contrato 18.1).
CREATE TABLE eventos_procesados (
    event_id     VARCHAR(100)             PRIMARY KEY,
    procesado_en TIMESTAMP WITH TIME ZONE NOT NULL
);
